import { randomBytes } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildDatabaseObjectCatalog, serializeDatabaseObjectCatalog } from './build-database-object-catalog.mjs'
import { computeBaselineFingerprint, sha256, sha256File } from './database-baseline-contract.mjs'
import { scanTextLine } from './scan-secrets.mjs'

const repoRoot = resolve(import.meta.dirname, '..')
const baselineId = 'eiscore-db-v1'
const postgresImage = 'postgres@sha256:f992505e18f114c1e5102ac4dcf00f791b44462f6a423d899320f0bbf80e386f'
const postgresVersion = '16.11 (Debian 16.11-1.pgdg13+1)'
const expectedSourceSha256 = 'c79e8d8f9640dd07a20fb6f03f4c5d036dbe7b8510c52eaea9f00cd8b2e9a9e5'
const restrictKey = `EISCOREDBBASELINEV1${'0'.repeat(44)}`
const maxOutput = 64 * 1024 * 1024

const normalizeRepoPath = (path) => String(path).replaceAll('\\', '/')
const relativeRepoPath = (path) => normalizeRepoPath(relative(repoRoot, path))
const sqlLiteral = (value) => `'${String(value).replaceAll("'", "''")}'`

const parseArgs = (argv) => {
  const sourceArg = argv.find((argument) => argument.startsWith('--source-dump='))
  const outputArg = argv.find((argument) => argument.startsWith('--output-dir='))
  return {
    sourceDump: resolve(repoRoot, sourceArg?.slice('--source-dump='.length) || 'tests/.artifacts/eiscore-g35-baseline.dump'),
    outputDir: resolve(repoRoot, outputArg?.slice('--output-dir='.length) || `database/baselines/${baselineId}`)
  }
}

const assertInsideRepo = (path, label) => {
  const relation = relative(repoRoot, path)
  if (!relation || relation === '..' || relation.startsWith(`..${sep}`)) {
    throw new Error(`${label} must be inside the repository`)
  }
}

const runDocker = (args, label, { quiet = true } = {}) => {
  const result = spawnSync('docker', args, {
    cwd: repoRoot,
    encoding: 'utf8',
    maxBuffer: maxOutput,
    windowsHide: true
  })
  if (result.error) throw new Error(`${label}: ${result.error.message}`)
  if (result.status !== 0) {
    const detail = String(result.stderr || result.stdout || '').trim()
    throw new Error(`${label} failed${detail ? `: ${detail}` : ''}`)
  }
  if (!quiet && result.stdout) process.stdout.write(result.stdout)
  return String(result.stdout || '').trim()
}

const waitForPostgres = (containerName) => {
  for (let attempt = 0; attempt < 30; attempt += 1) {
    const result = spawnSync('docker', ['exec', containerName, 'pg_isready', '-U', 'postgres', '-d', 'postgres'], {
      encoding: 'utf8',
      windowsHide: true
    })
    if (result.status === 0) return
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 1000)
  }
  throw new Error('isolated PostgreSQL did not become ready within 30 seconds')
}

const readManifestMigrations = (manifestPath) => {
  const manifest = JSON.parse(readFileSync(resolve(repoRoot, manifestPath), 'utf8'))
  return manifest.migrations.map(({ id, sha256: checksum }) => ({
    id,
    sha256: checksum,
    sourceManifest: manifestPath
  }))
}

const renderRegistration = (manifest) => {
  const coverageValues = manifest.coveredMigrations.map((entry) => `  (${[
    manifest.baselineId,
    entry.id,
    entry.sha256,
    entry.sourceManifest
  ].map(sqlLiteral).join(', ')})`).join(',\n')
  const expectedCount = manifest.coveredMigrations.length
  return `-- SPDX-License-Identifier: AGPL-3.0-or-later
-- Copyright (c) 2026 林志荣
-- Generated by scripts/build-database-baseline.mjs; contains release metadata only.

\\set ON_ERROR_STOP on

BEGIN;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM eiscore_meta.database_baselines
    WHERE baseline_id = ${sqlLiteral(manifest.baselineId)}
      AND (
        baseline_fingerprint_sha256 <> ${sqlLiteral(manifest.fingerprintSha256)}
        OR schema_sha256 <> ${sqlLiteral(manifest.schema.sha256)}
        OR object_catalog_sha256 <> ${sqlLiteral(manifest.objectCatalog.sha256)}
      )
  ) THEN
    RAISE EXCEPTION 'baseline identity conflict: ${manifest.baselineId}';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM eiscore_meta.baseline_migration_coverage c
    JOIN (VALUES
${coverageValues}
    ) AS expected(baseline_id, migration_id, checksum_sha256, source_manifest)
      ON expected.baseline_id = c.baseline_id
     AND expected.migration_id = c.migration_id
    WHERE c.checksum_sha256 <> expected.checksum_sha256
       OR c.source_manifest <> expected.source_manifest
  ) THEN
    RAISE EXCEPTION 'baseline migration coverage checksum conflict: ${manifest.baselineId}';
  END IF;
END
$$;

INSERT INTO eiscore_meta.database_baselines (
  baseline_id,
  baseline_fingerprint_sha256,
  schema_sha256,
  object_catalog_sha256
) VALUES (
  ${sqlLiteral(manifest.baselineId)},
  ${sqlLiteral(manifest.fingerprintSha256)},
  ${sqlLiteral(manifest.schema.sha256)},
  ${sqlLiteral(manifest.objectCatalog.sha256)}
)
ON CONFLICT (baseline_id) DO NOTHING;

INSERT INTO eiscore_meta.baseline_migration_coverage (
  baseline_id,
  migration_id,
  checksum_sha256,
  source_manifest
) VALUES
${coverageValues}
ON CONFLICT (baseline_id, migration_id) DO NOTHING;

DO $$
BEGIN
  IF (
    SELECT count(*)
    FROM eiscore_meta.baseline_migration_coverage
    WHERE baseline_id = ${sqlLiteral(manifest.baselineId)}
  ) <> ${expectedCount} THEN
    RAISE EXCEPTION 'baseline migration coverage conflict: ${manifest.baselineId}';
  END IF;
END
$$;

COMMIT;
`
}

export const buildDatabaseBaseline = ({ sourceDump, outputDir }) => {
  assertInsideRepo(sourceDump, 'source dump')
  assertInsideRepo(outputDir, 'output directory')
  if (!existsSync(sourceDump)) throw new Error(`source dump does not exist: ${relativeRepoPath(sourceDump)}`)
  if (sha256File(sourceDump) !== expectedSourceSha256) throw new Error('source dump checksum does not match accepted DB1 evidence')
  if (existsSync(outputDir) && readdirSync(outputDir).length > 0) {
    throw new Error(`output directory must be absent or empty: ${relativeRepoPath(outputDir)}`)
  }
  mkdirSync(outputDir, { recursive: true })

  const containerName = `eiscore-db1-baseline-${process.pid}-${randomBytes(4).toString('hex')}`
  let created = false
  try {
    runDocker([
      'run', '-d', '--name', containerName,
      '--network', 'none', '--read-only',
      '--tmpfs', '/var/lib/postgresql/data:rw,noexec,nosuid,size=2g',
      '--tmpfs', '/var/run/postgresql:rw,noexec,nosuid,size=16m',
      '--tmpfs', '/tmp:rw,noexec,nosuid,size=64m',
      '--shm-size', '256m',
      '-e', 'POSTGRES_HOST_AUTH_METHOD=trust',
      '--mount', `type=bind,source=${repoRoot},target=/repo,readonly`,
      '--mount', `type=bind,source=${sourceDump},target=/input/eiscore.dump,readonly`,
      '--mount', `type=bind,source=${outputDir},target=/output`,
      postgresImage
    ], 'isolated baseline container start')
    created = true
    waitForPostgres(containerName)

    const psqlFile = (path, label) => runDocker([
      'exec', containerName, 'psql', '-v', 'ON_ERROR_STOP=1', '-U', 'postgres', '-d', 'postgres', '-f', path
    ], label)
    psqlFile('/repo/env/init_roles.sql', 'role bootstrap')
    runDocker([
      'exec', containerName, 'pg_restore', '--exit-on-error', '--no-owner',
      '-U', 'postgres', '-d', 'postgres', '/input/eiscore.dump'
    ], 'predecessor dump restore')
    psqlFile('/repo/sql/runtime_v2_postcheck.sql', 'Runtime V2 predecessor verification')
    psqlFile('/repo/sql/company_site_platform_v1.sql', 'company-site schema adoption')
    psqlFile('/repo/database/migrations/sql/company-site-001-add-published-snapshot.sql', 'company-site migration')
    psqlFile('/repo/database/migrations/postchecks/company-site.sql', 'company-site postcheck')
    psqlFile('/repo/database/migrations/sql/core-001-externalize-database-credentials.sql', 'core credential migration')
    psqlFile('/repo/database/migrations/postchecks/core.sql', 'core postcheck')
    psqlFile('/repo/database/migration-ledger.sql', 'migration metadata schema')
    runDocker([
      'exec', containerName, 'pg_dump', '--schema-only', '--no-owner',
      `--restrict-key=${restrictKey}`, '--username=postgres', '--dbname=postgres', '--file=/output/schema.sql'
    ], 'canonical schema dump')
  } finally {
    if (created) runDocker(['rm', '-f', '-v', containerName], 'isolated baseline container cleanup')
  }

  const schemaPath = resolve(outputDir, 'schema.sql')
  const schemaBuffer = readFileSync(schemaPath)
  const schemaText = schemaBuffer.toString('utf8')
  for (const forbidden of [
    [/^-- Data for Name:/m, 'table data marker'],
    [/^COPY\s/m, 'COPY data'],
    [/OWNER TO/i, 'object owner']
  ]) if (forbidden[0].test(schemaText)) throw new Error(`canonical schema contains ${forbidden[1]}`)
  const customerBinding = /君乐缘|经纬|伦度|junleyuan|jinwei|lundun|nanpai|eissys/i
  if (customerBinding.test(schemaText)) throw new Error('canonical schema contains a customer binding')
  const secretFindings = schemaText.split(/\r?\n/).flatMap((line, index) => scanTextLine({
    path: relativeRepoPath(schemaPath),
    line,
    lineNumber: index + 1
  }))
  if (secretFindings.length) throw new Error(`canonical schema contains ${secretFindings.length} secret finding(s)`)

  const catalog = buildDatabaseObjectCatalog(schemaBuffer)
  const catalogText = serializeDatabaseObjectCatalog(catalog)
  const catalogPath = resolve(outputDir, 'object-catalog.json')
  writeFileSync(catalogPath, catalogText)

  const rolePath = 'env/init_roles.sql'
  const adoptionPath = 'sql/company_site_platform_v1.sql'
  const coveredMigrations = [
    ...readManifestMigrations('database/migrations/runtime-v2.json'),
    ...readManifestMigrations('database/migrations/company-site.json'),
    ...readManifestMigrations('database/migrations/core.json')
  ]
  const manifest = {
    schemaVersion: 1,
    baselineId,
    postgres: {
      major: 16,
      version: postgresVersion,
      image: postgresImage,
      restrictKey
    },
    sourceEvidence: {
      kind: 'local-custom-dump-audit-evidence',
      sha256: expectedSourceSha256,
      releaseInput: false,
      verifiedBy: 'sql/runtime_v2_postcheck.sql'
    },
    roleBootstrap: { path: rolePath, sha256: sha256File(resolve(repoRoot, rolePath)) },
    runtimeSecretBootstrap: {
      path: 'scripts/configure-database-runtime-secret.sh',
      sha256: sha256File(resolve(repoRoot, 'scripts/configure-database-runtime-secret.sh'))
    },
    legacySchemaAdoptions: [
      {
        id: 'company-site-platform-v1',
        path: adoptionPath,
        sha256: sha256File(resolve(repoRoot, adoptionPath)),
        classification: 'schema-fragment',
        releaseInput: false
      }
    ],
    schema: {
      path: `${relativeRepoPath(outputDir)}/schema.sql`,
      sha256: sha256(schemaBuffer),
      bytes: schemaBuffer.length
    },
    objectCatalog: {
      path: `${relativeRepoPath(outputDir)}/object-catalog.json`,
      sha256: sha256(Buffer.from(catalogText, 'utf8')),
      objectCount: catalog.objectCount
    },
    coveredMigrations,
    installOrder: [
      rolePath,
      `${relativeRepoPath(outputDir)}/schema.sql`,
      `${relativeRepoPath(outputDir)}/register.sql`,
      'scripts/configure-database-runtime-secret.sh'
    ],
    upgradeProfiles: [
      {
        predecessorId: 'g35-runtime-v2',
        verifiedPreexistingManifests: ['database/migrations/runtime-v2.json'],
        schemaAdoptions: ['company-site-platform-v1'],
        pendingMigrationManifests: [
          'database/migrations/company-site.json',
          'database/migrations/core.json'
        ],
        equivalenceTargetSha256: sha256(schemaBuffer)
      }
    ],
    excludedReleaseInputs: [
      'db_schema_and_data.sql',
      'tests/.artifacts/eiscore-g35-baseline.dump',
      'sql/company_site_platform_v1.sql'
    ],
    contentGuarantees: {
      businessRows: 0,
      customerBindings: 0,
      embeddedCredentials: 0,
      ownerStatements: 0,
      privilegeStatements: (schemaText.match(/^(?:GRANT|REVOKE)\s/gim) || []).length,
      registrationRows: coveredMigrations.length + 1
    }
  }
  manifest.fingerprintSha256 = computeBaselineFingerprint(manifest)

  const registrationText = renderRegistration(manifest)
  const registrationPath = resolve(outputDir, 'register.sql')
  writeFileSync(registrationPath, registrationText)
  manifest.registration = {
    path: `${relativeRepoPath(outputDir)}/register.sql`,
    sha256: sha256(Buffer.from(registrationText, 'utf8')),
    rows: coveredMigrations.length + 1
  }
  writeFileSync(resolve(outputDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
  return manifest
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  try {
    const manifest = buildDatabaseBaseline(parseArgs(process.argv.slice(2)))
    console.log(`PASS: ${manifest.baselineId} generated (${manifest.objectCatalog.objectCount} objects, ${manifest.coveredMigrations.length} covered migrations)`)
  } catch (error) {
    console.error(`[error] ${error.message}`)
    process.exitCode = 1
  }
}
